// ─── Formatting helpers ───────────────────────────────────────────────────────

pub(super) fn fmt_ip(b: &[u8]) -> String {
    if b.len() < 4 {
        return "0.0.0.0".into();
    }
    format!("{}.{}.{}.{}", b[0], b[1], b[2], b[3])
}

pub(super) fn fmt_ipv6(b: &[u8]) -> String {
    if b.len() < 16 {
        return "::".into();
    }
    b.chunks(2)
        .map(|c| format!("{:02x}{:02x}", c[0], c[1]))
        .collect::<Vec<_>>()
        .join(":")
}

pub(super) fn fmt_tcp_flags(f: u8) -> String {
    let mut s = String::new();
    if f & 0x02 != 0 {
        s.push_str("SYN ");
    }
    if f & 0x10 != 0 {
        s.push_str("ACK ");
    }
    if f & 0x01 != 0 {
        s.push_str("FIN ");
    }
    if f & 0x04 != 0 {
        s.push_str("RST ");
    }
    if f & 0x08 != 0 {
        s.push_str("PSH ");
    }
    if f & 0x20 != 0 {
        s.push_str("URG ");
    }
    if s.is_empty() {
        s.push_str("NONE");
    }
    s.trim_end().to_string()
}
